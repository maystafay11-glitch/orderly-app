// حالة تشغيل عنصر الفيديو الخاص بالكاميرا على الويب.
//
// تُستخدم في شاشة المسح للتأكد من أن معاينة الكاميرا تعمل فعلاً، لأن بعض
// المتصفحات (Safari في iOS خصوصاً) تحتاج `playsinline` و`muted` و`autoplay`
// على عنصر `<video>` وإلا تبقى المعاينة سوداء أو تتوقف بعد ثانية.
enum WebCameraPlaybackState {
  /// لا ينطبق: المنصة أصلية (Android/iOS) وليست متصفحاً.
  notApplicable,

  /// لم يُعثر على عنصر فيديو كاميرا في الصفحة.
  videoNotFound,

  /// عنصر الفيديو موجود ويعرض البث الآن.
  playing,

  /// عنصر الفيديو موجود لكنه متوقف (يحتاج لمسة من المستخدم أو إعادة تشغيل).
  paused,
}
